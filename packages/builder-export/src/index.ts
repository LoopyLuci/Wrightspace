export function getProjectFilesFromDoc(doc: Y.Doc): ExportProjectFiles {
  return buildProjectFiles(readPageCodeFromDoc(doc));
}

export async function exportProject(doc: Y.Doc): Promise<Buffer> {
  return exportProjectFromFiles(getProjectFilesFromDoc(doc));
}

export async function exportProjectFromFiles(files: ExportProjectFiles): Promise<Buffer> {
  const zip = new JSZip();
  for (const [path, content] of Object.entries(files)) {
    zip.file(path, content);
  }

  return zip.generateAsync({ type: "nodebuffer" });
}

export async function createProjectTarball(files: ExportProjectFiles): Promise<Buffer> {
  const pack = tar.pack();

  for (const [name, body] of Object.entries(files)) {
    pack.entry({ name }, body);
  }

  pack.finalize();

  const chunks: Buffer[] = [];
  for await (const chunk of pack) {
    chunks.push(Buffer.from(chunk));
  }

  return Buffer.concat(chunks);
}

export function createDocFromSnapshot(input: ExportSnapshotInput): Y.Doc {
  const doc = new Y.Doc();
  const workspace = doc.getMap(WORKSPACE_KEY);
  const sourceText = doc.getText(`source:${input.projectId}:app/page.tsx`);

  sourceText.insert(0, input.pageCode);
  workspace.set("code", input.pageCode);

  if (input.irSnapshot) {
    workspace.set("ir", input.irSnapshot);
  }

  return doc;
}
