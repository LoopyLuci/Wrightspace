import JSZip from "jszip";
import tar from "tar-stream";
import * as Y from "yjs";

const WORKSPACE_KEY = "workspace";
const SOURCE_FILE_SUFFIX = ":app/page.tsx";

export type ExportProjectFiles = Record<string, string>;

export interface ExportSnapshotInput {
  projectId: string;
  pageCode: string;
  irSnapshot?: string | null;
}

function getFirstSourceText(doc: Y.Doc): Y.Text | null {
  const share = (doc as unknown as { share?: Map<string, Y.AbstractType<Y.Doc>> }).share;
  if (!share) {
    return null;
  }

  for (const key of share.keys()) {
    if (key.startsWith("source:") && key.endsWith(SOURCE_FILE_SUFFIX)) {
      return doc.getText(key);
    }
  }

  return null;
}

export function readPageCodeFromDoc(doc: Y.Doc): string {
  const workspace = doc.getMap(WORKSPACE_KEY) as Y.Map<unknown>;
  const workspaceCode = workspace.get("code");
  if (typeof workspaceCode === "string" && workspaceCode.trim().length > 0) {
    return workspaceCode;
  }

  const sourceText = getFirstSourceText(doc);
  if (sourceText) {
    const code = sourceText.toString();
    if (code.trim().length > 0) {
      return code;
    }
  }

  return `import React from "react";

export default function Home() {
  return (
    <main className="min-h-screen grid place-items-center p-16">
      <section className="max-w-3xl rounded-3xl border border-slate-200 bg-white p-10 shadow-xl">
        <h1 className="text-4xl font-bold text-slate-900">Exported from WebBuilder</h1>
        <p className="mt-4 text-slate-700">Start editing src/app/page.tsx and deploy when ready.</p>
      </section>
    </main>
  );
}`;
}

